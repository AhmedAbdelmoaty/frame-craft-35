export function failureDialogue(reason: "chose_corniche" | "midan_weak_evidence" | "incomplete"): ResultDialogue {
  if (reason === "chose_corniche") {
    return {
      title: "توصية غير قابلة للدفاع",
      badge: "رُدّت التوصية",
      nader: "لا أستطيع الدفاع عن هذه التوصية. الرقم الأعلى لا يكفي وحده.",
      layla:
        "السياسة تقيس المندوب الفرد لا المتوسط. ٧ من ١٠ في الكورنيش تحت ٨٥٪ — مكافأتهم تضرب السياسة.",
      emad: "أنا قلتها من البداية، لكن الرقم بدون قراءة للفريق ليس دليلًا.",
      lesson: [
        "وقعت في فخ المتوسط: متوسط ٩٦٪ يخفي أن غالبية الفريق تحت العتبة.",
        "ثلاثة outliers بأداء ١٥٠٪ هم من رفعوا الرقم، لا أداء جماعي.",
        "القرار العادل: انظر لتوزيع الفريق، لا للرقم الواحد.",
      ],
    };
  }
  if (reason === "midan_weak_evidence") {
    return {
      title: "توصية غير قابلة للدفاع",
      badge: "اتجاه صحيح — دليل ناقص",
      nader: "اتجاهك سليم، لكن أحتاج دليلين تحليليين واضحين للدفاع أمام الإدارة.",
      layla: "السياسة وحدها سياق — أريد أرقامًا من بيانات الفروع تثبت الأداء الجماعي.",
      emad: "المتوسط أو إجمالي المبيعات أو السياسة وحدها لا تكفي. أحضر تحليلًا.",
      lesson: [
        "اختيار الفرع الصحيح وحده لا يصنع توصية قابلة للدفاع.",
        "الأدلة القوية تأتي من التحليل: توزيع ٨٥٪، الوسيط، الاستقرار، أو القيم الاستثنائية.",
        "المتوسط وإجمالي المبيعات وسياسة HR وحدها أدلة سطحية لا تدعم الميدان.",
      ],
    };
  }
  return {
    title: "توصية غير مكتملة",
    badge: "بيانات ناقصة",
    nader: "لم تكتمل توصيتك. اختر فرعًا ودليلين.",
    layla: "بدون قرار واضح لا يمكنني الموافقة.",
    emad: "نحتاج تفاصيل أكثر.",
    lesson: ["أكمل اختيار الفرع والدليلين قبل التقديم."],
  };
}
